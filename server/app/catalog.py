"""
catalog.py — loads /catalog/catalog.json (maintenance types, spec fields,
manufacturer links) so the rest of the server can look things up.

The JSON file is generated by catalog/build_catalog.py and shared with the
web and Android apps.
"""

from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path

from .config import asset_path


def _catalog_path() -> Path:
    """Find catalog.json: an explicit setting, else the repo/Docker/desktop copy."""
    explicit = os.environ.get("RW_CATALOG_PATH")
    if explicit and Path(explicit).is_file():
        return Path(explicit)
    path = asset_path("catalog", "catalog.json")
    if not path.is_file():
        raise FileNotFoundError("catalog.json not found; run catalog/build_catalog.py")
    return path


@lru_cache(maxsize=1)
def load_catalog() -> dict:
    """The whole catalog as a dictionary (read once, then cached)."""
    return json.loads(_catalog_path().read_text(encoding="utf-8"))


def type_keys() -> set[str]:
    """All valid maintenance/repair type keys."""
    return {t["key"] for t in load_catalog()["types"]}


def type_label(key: str) -> str:
    """Human label for a type key ('oil_change' -> 'Oil change')."""
    for t in load_catalog()["types"]:
        if t["key"] == key:
            return t["label"]
    return "Custom / other"


def spec_keys() -> set[str]:
    """All valid spec field keys."""
    return {s["key"] for s in load_catalog()["specs"]}


def spec_label(key: str) -> str:
    """Human label for a spec key."""
    for s in load_catalog()["specs"]:
        if s["key"] == key:
            return s["label"]
    return key


SPEC_SOURCES = {"vin", "sticker", "user", "unverified", "provider", "carfax"}


def make_links(make: str, kind: str = "car") -> dict:
    """Official parts site and owner portal for a make (case-insensitive).
    Makes that build cars AND motorcycles (Honda, BMW...) may have separate
    motorcycle links ("moto_parts" / "moto_owners").

    Returns {"parts": url|None, "owners": url|None}.  Never a dealer site."""
    makes = load_catalog()["makes"]
    for name, links in makes.items():
        if name.lower() == (make or "").strip().lower():
            owners = links.get("owners")
            parts = links.get("parts")
            if kind == "motorcycle" and (links.get("moto_parts") or links.get("moto_owners")):
                owners = links.get("moto_owners") or owners
                parts = links.get("moto_parts")
            return {"parts": parts or owners, "owners": owners}
    return {"parts": None, "owners": None}
